"""A run file in a few lines, without its grids (runs/*.json can be 1.6 MB:
never read them whole). usage: runsummary.py [NAME ...]   (no NAME: write
runs/INDEX.md, one line per run)"""
import glob, json, os, sys, time

RUNS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "runs")


def summary(path):
    d = json.load(open(path))
    if not isinstance(d, dict):
        return f"list of {len(d)}"
    recs = d.get("records") if isinstance(d.get("records"), list) else []
    keys = sorted({k for r in recs[:50] if isinstance(r, dict) for k in r if k != "grid"})
    axes = []
    for k in ("target", "backlight", "step", "level", "code"):
        vals = sorted({r[k] for r in recs if isinstance(r, dict) and isinstance(r.get(k), (int, float))})
        if vals:
            axes.append(f"{k} {vals[0]}-{vals[-1]} ({len(vals)})")
    meta = {k: v for k, v in d.items() if k not in ("records", "accuracy", "summary", "conditions", "grid")
            and not isinstance(v, (list, dict))}
    extra = [k for k in ("accuracy", "summary", "conditions") if k in d]
    return (f"{len(recs)} records; " + ", ".join(axes) + (f"; meta {meta}" if meta else "")
            + (f"; also {', '.join(extra)}" if extra else "") + (f"; fields {', '.join(keys)}" if keys else ""))


if len(sys.argv) > 1:
    for n in sys.argv[1:]:
        p = n if n.endswith(".json") else os.path.join(RUNS, n + ".json")
        print(f"{os.path.basename(p)}: {summary(p)}")
else:
    lines = ["# Runs (generated by runsummary.py; one line each, newest first)", "",
             "Never read a run file whole (grids: up to 1.6 MB). `python3 runsummary.py NAME` for one.", ""]
    for p in sorted(glob.glob(os.path.join(RUNS, "*.json")), key=os.path.getmtime, reverse=True):
        try:
            s = summary(p)
        except (ValueError, OSError) as e:
            s = f"unreadable ({e})"
        lines.append(f"- `{os.path.basename(p)}` {time.strftime('%m-%d %H:%M', time.localtime(os.path.getmtime(p)))}, "
                     f"{os.path.getsize(p) // 1024} KB: {s}")
    open(os.path.join(RUNS, "INDEX.md"), "w").write("\n".join(lines) + "\n")
    print(f"wrote runs/INDEX.md ({len(lines) - 4} runs)")
